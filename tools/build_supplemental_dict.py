"""
Build and merge supplemental Japanese/English conversion dictionaries for Meltype Android.

Extracts katakana loanwords, compound nouns, and reading->surface mappings from bundled
JMdict/Wiktionary resources (meanings.txt, translations.txt, readings.txt) and merges
curated modern IT/AI, payment, entertainment, regional, science/engineering, and
colloquial/SNS vocabulary idempotently into:
  - app/src/main/assets/dictionaries/brands.txt
  - app/src/main/assets/dictionaries/candidates.txt
  - app/src/main/assets/dictionaries/phrases.txt
  - app/src/main/assets/dictionaries/propernouns.txt
  - app/src/main/assets/dictionaries/english-readable.txt
  - app/src/main/assets/dictionaries/english.txt
"""

from __future__ import annotations

import pathlib
import re
from collections import OrderedDict

ROOT = pathlib.Path(__file__).resolve().parent.parent
DICT_DIR = ROOT / "app" / "src" / "main" / "assets" / "dictionaries"
MARKER = "# --- Supplemental v1.12.0 (generated by tools/build_supplemental_dict.py) ---"

HIRAGANA_RE = re.compile(r"^[\u3041-\u3096ー]+$")
KATAKANA_RE = re.compile(r"^[\u30A1-\u30F6ー]+$")
HAS_KANJI_OR_KATA_RE = re.compile(r"[\u4E00-\u9FFF\u30A1-\u30F6]")
FOREIGN_KANA_CLUSTER_RE = re.compile(r"(ー|ふぁ|ふぃ|ふぇ|ふぉ|てぃ|でぃ|とぅ|どぅ|うぃ|うぇ|うぉ|しぇ|じぇ|ちぇ|つぁ|つぃ|つぇ|つぉ|ゔ)")


def kata_to_hira(text: str) -> str:
    out = []
    for ch in text:
        code = ord(ch)
        if 0x30A1 <= code <= 0x30F6:
            out.append(chr(code - 0x60))
        else:
            out.append(ch)
    return "".join(out)


def hira_to_kata(text: str) -> str:
    out = []
    for ch in text:
        code = ord(ch)
        if 0x3041 <= code <= 0x3096:
            out.append(chr(code + 0x60))
        else:
            out.append(ch)
    return "".join(out)


def strip_generated_section(text: str) -> str:
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.strip() == MARKER:
            while i > 0 and not lines[i - 1].strip():
                i -= 1
            return "\n".join(lines[:i])
    return "\n".join(lines).rstrip()


def parse_existing_kv_map(text: str) -> dict[str, list[str]]:
    res: dict[str, list[str]] = {}
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split("\t") if p.strip()] if "\t" in line else line.split()
        if len(parts) >= 2:
            res.setdefault(parts[0], [])
            for v in parts[1:]:
                if v not in res[parts[0]]:
                    res[parts[0]].append(v)
    return res


def parse_existing_phrases(text: str) -> dict[str, str]:
    res: dict[str, str] = {}
    for raw in text.splitlines():
        s = raw.strip()
        if not s or s.startswith("#") or "\t" not in s:
            continue
        r, w = s.split("\t", 1)
        r = r.lstrip("^").replace("|", "").strip()
        w = w.replace("|", "").strip()
        if r and w:
            res.setdefault(r, w)
    return res


def parse_existing_words(text: str) -> set[str]:
    words: set[str] = set()
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if "\t" in line:
            key = line.split("\t", 1)[0].strip().lower()
            if key:
                words.add(key)
        else:
            for tok in line.split():
                words.add(tok.lower())
    return words


def extract_from_jmdict_resources() -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """
    Extract reading -> surface candidates from meanings.txt, translations.txt, and readings.txt.
    Returns (extra_candidates, katakana_loanwords).
    """
    readings_path = DICT_DIR / "readings.txt"
    meanings_path = DICT_DIR / "meanings.txt"
    translations_path = DICT_DIR / "translations.txt"

    known_readings: set[str] = set()
    loanword_readings: list[str] = []
    if readings_path.is_file():
        for raw in readings_path.read_text(encoding="utf-8").splitlines():
            s = raw.strip()
            if not s or s.startswith("#"):
                continue
            r = s.split("\t", 1)[0].strip()
            if HIRAGANA_RE.match(r):
                known_readings.add(r)
                if len(r) >= 4 and FOREIGN_KANA_CLUSTER_RE.search(r):
                    loanword_readings.append(r)

    extracted_cands: OrderedDict[str, list[str]] = OrderedDict()

    def add_cand(reading: str, surface: str) -> None:
        if not reading or not surface or reading == surface:
            return
        if not HIRAGANA_RE.match(reading) or len(reading) < 3 or len(reading) > 20:
            return
        if any(c in surface for c in (" ", "\t", "　", "・", "〈", "〉", "《", "》")):
            return
        bucket = extracted_cands.setdefault(reading, [])
        if surface not in bucket:
            bucket.append(surface)

    # 1. Explicit reading rows in meanings.txt (surface \t reading \t definition)
    if meanings_path.is_file():
        for raw in meanings_path.read_text(encoding="utf-8").splitlines():
            if not raw or raw.startswith("#"):
                continue
            parts = raw.split("\t")
            if len(parts) < 3:
                continue
            surface = parts[0].strip()
            reading = parts[1].strip()
            if not surface or not reading:
                continue
            if HIRAGANA_RE.match(reading) and HAS_KANJI_OR_KATA_RE.search(surface):
                if len(surface) <= 16:
                    add_cand(reading, surface)

    # 2. Compound/katakana noun entries in translations.txt matched against known readings
    #    plus pure-katakana words in translations.txt / meanings.txt
    for src_path in (translations_path, meanings_path):
        if not src_path.is_file():
            continue
        for raw in src_path.read_text(encoding="utf-8").splitlines():
            if not raw or raw.startswith("#"):
                continue
            surface = raw.split("\t", 1)[0].strip()
            if not surface or len(surface) < 3 or len(surface) > 18:
                continue
            if KATAKANA_RE.match(surface):
                hira = kata_to_hira(surface)
                if len(hira) >= 3:
                    add_cand(hira, surface)

    # 3. Loanword katakana readings from readings.txt (explicit foreign clusters / prolonged vowels)
    katakana_loans: OrderedDict[str, list[str]] = OrderedDict()
    for r in loanword_readings:
        kata = hira_to_kata(r)
        if kata != r and len(r) >= 4:
            katakana_loans.setdefault(r, [kata])

    return extracted_cands, katakana_loans


