def format_kv_line(key: str, values: list[str]) -> str:
    if any(" " in v for v in values):
        return "\t".join([key] + values)
    return " ".join([key] + values)


def write_with_supplemental_section(path: pathlib.Path, extra_lines: list[str]) -> None:
    base = strip_generated_section(path.read_text(encoding="utf-8"))
    parts = [base.rstrip(), "", MARKER, *extra_lines, ""]
    path.write_text("\n".join(parts), encoding="utf-8")


def main() -> int:
    jmdict_cands, jmdict_loans = extract_from_jmdict_resources()

    # 1. brands.txt
    brands_path = DICT_DIR / "brands.txt"
    existing_brands = parse_existing_kv_map(strip_generated_section(brands_path.read_text(encoding="utf-8")))
    brand_lines: list[str] = []
    for r, cands in CURATED_BRANDS:
        new_cands = [c for c in cands if c not in existing_brands.get(r, [])]
        if new_cands:
            brand_lines.append(format_kv_line(r, new_cands))
    write_with_supplemental_section(brands_path, brand_lines)

    # 2. candidates.txt
    cands_path = DICT_DIR / "candidates.txt"
    existing_cands = parse_existing_kv_map(strip_generated_section(cands_path.read_text(encoding="utf-8")))
    cand_map: OrderedDict[str, list[str]] = OrderedDict()

    def add_cand_entry(r: str, vals: list[str]) -> None:
        cur = existing_cands.get(r, [])
        bucket = cand_map.setdefault(r, [])
        for v in vals:
            if v not in cur and v not in bucket:
                bucket.append(v)

    for r, vals in CURATED_PLACES + CURATED_TECH_SCIENCE + CURATED_COLLOQUIAL:
        add_cand_entry(r, vals)
    for r, vals in jmdict_cands.items():
        add_cand_entry(r, vals)
    for r, vals in jmdict_loans.items():
        add_cand_entry(r, vals)

    cand_lines = [format_kv_line(r, vals) for r, vals in cand_map.items() if vals]
    write_with_supplemental_section(cands_path, cand_lines)

    # 3. phrases.txt
    phrases_path = DICT_DIR / "phrases.txt"
    existing_phrases = parse_existing_phrases(strip_generated_section(phrases_path.read_text(encoding="utf-8")))
    phrase_lines: list[str] = []
    seen_phrase_keys = set(existing_phrases.keys())
    for r, w in CURATED_PHRASES:
        plain_r = r.lstrip("^").replace("|", "")
        if plain_r not in seen_phrase_keys:
            seen_phrase_keys.add(plain_r)
            phrase_lines.append(f"{r}\t{w}")
    write_with_supplemental_section(phrases_path, phrase_lines)

    # 4. propernouns.txt
    proper_path = DICT_DIR / "propernouns.txt"
    existing_proper = parse_existing_words(strip_generated_section(proper_path.read_text(encoding="utf-8")))
    proper_lines: list[str] = []
    for entry in CURATED_PROPER_NOUNS:
        key = entry.split("\t", 1)[0].strip().lower()
        if key not in existing_proper:
            existing_proper.add(key)
            proper_lines.append(entry)
    write_with_supplemental_section(proper_path, proper_lines)

    # 5. english-readable.txt
    er_path = DICT_DIR / "english-readable.txt"
    existing_er = parse_existing_words(strip_generated_section(er_path.read_text(encoding="utf-8")))
    er_new = [w for w in CURATED_READABLE_ENGLISH if w.lower() not in existing_er]
    write_with_supplemental_section(er_path, [" ".join(er_new)] if er_new else [])

    # 6. english.txt
    en_path = DICT_DIR / "english.txt"
    existing_en = parse_existing_words(strip_generated_section(en_path.read_text(encoding="utf-8")))
    en_new = [w for w in CURATED_COMMON_ENGLISH if w.lower() not in existing_en]
    write_with_supplemental_section(en_path, [" ".join(en_new)] if en_new else [])

    print(
        f"Updated supplemental dictionaries: "
        f"brands=+{len(brand_lines)}, candidates=+{len(cand_lines)}, "
        f"phrases=+{len(phrase_lines)}, propernouns=+{len(proper_lines)}, "
        f"english-readable=+{len(er_new)}, english=+{len(en_new)}"
    )
    return 0


